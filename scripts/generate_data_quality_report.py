"""Generates docs/DATA_QUALITY_REPORT.md from the real knowledge base. Nothing is auto-corrected:
every irregularity found is listed so the data owner can fix it at the source."""

import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from pathfinder.api.settings import Settings  # noqa: E402
from pathfinder.engine import Engine  # noqa: E402
from pathfinder.knowledge import load_knowledge_base_from_dir  # noqa: E402

cfg = Settings.from_env({})
kb = load_knowledge_base_from_dir(str(cfg.kb_dir))
engine = Engine(kb)

by_code: dict[str, list[dict]] = {}
for i in [*kb.issues, *engine.issues]:
    by_code.setdefault(i["code"], []).append(i)
costs = Counter(r.access["cost"] for r in kb.resources.values())
verification = Counter(r.verification_status for r in kb.resources.values())

HOW = {
    "PROJECT_CATEGORY_MISMATCH": "Held back from every recommendation and roadmap. Fix: confirm the correct career for these projects in the source data (their titles suggest security topics, but they carry the AI/ML source id) and set `career_id`.",
    "DUPLICATE_URL": "Different resource ids point to the same URL. The engine lists each URL once per roadmap (first stage wins). Fix: merge duplicates or keep them deliberately distinct.",
    "RESOURCES_NOT_IN_ANY_STAGE": "These resources are in the archive but no roadmap stage references them, so they are never recommended. Fix: attach them to a stage or drop them.",
    "RESOURCE_NO_URL": "Shown without a link; the engine never invents one. Fix: supply the real URL.",
    "PROJECT_SKILLS_BY_NAME": "Newer projects list skill names instead of `skill_id`s, so they cannot be linked to skill records. Shown as text. Fix: use skill ids.",
    "ACTIVITY_NO_RESOURCE": "Activities such as milestones or networking tasks carry no resource. Shown as plain activities.",
    "OPPORTUNITY_NO_URL": "Opportunity lead without a URL; shown without a link.",
}

try:
    kb_rel = str(cfg.kb_dir.relative_to(ROOT))
except ValueError:
    kb_rel = str(cfg.kb_dir)

md = f"""# Knowledge-base data-quality report

Generated by `python scripts/generate_data_quality_report.py` from `{kb_rel}` (knowledge base v{kb.version}). **Nothing here was silently corrected.**

## Summary

| Collection | Records |
|---|---|
{chr(10).join(f'| {k} | {v} |' for k, v in kb.counts.items())}

Resource cost signals (derived only from the records' own notes): {', '.join(f'{k}: {v}' for k, v in costs.items())}.
Resource verification statuses: {', '.join(f'`{k}`: {v}' for k, v in verification.items())}.

> The archive validates **structure only** (unique ids, references). It does not verify links, course availability, prices, eligibility, deadlines or funding. The engine therefore never calls a resource "free", "verified", "open" or "funded", and shows every opportunity as an unverified lead.

## Findings

| Code | Severity | Count | What the engine does |
|---|---|---|---|
"""
for code in sorted(by_code):
    lst = by_code[code]
    md += f"| `{code}` | {lst[0]['severity']} | {len(lst)} | {HOW.get(code) or lst[0]['message']} |\n"

md += "\n## Details\n"
for code in sorted(by_code):
    lst = by_code[code]
    md += f"\n### {code}\n\n"
    for i in lst[:12]:
        md += f"- {i['message']}\n"
    if len(lst) > 12:
        md += f"- …and {len(lst) - 12} more\n"
md += """
## Structural limits of the data that affect recommendations

- **No career-attribute fields.** No record says which interests, strengths, work styles or goals suit a career, so matching uses a manually maintained, evidence-annotated taxonomy (`pathfinder/engine/taxonomy.py`, see docs/SCORING_AND_MAPPING.md).
- **Prerequisites are free text** (or null) and cannot be checked automatically. They are shown verbatim as "per source".
- **Projects are linked to careers, not to roadmap stages.** The engine says so instead of guessing a stage.
- **Stage shapes differ between careers** (e.g. Data Careers is a process plan with a 12-week schedule, not four difficulty levels). The loader maps all shapes to one structure.
- **No application status or deadline exists for any opportunity.** All are `unverified_lead`.
- **No maths-specific learning resources exist**, although several paths benefit from maths. The roadmap states this gap.
- **No resource states device requirements** (only Intro to Coding states a path-level setup requirement), and no resource states offline availability.
"""
(ROOT / "docs" / "DATA_QUALITY_REPORT.md").write_text(md, "utf-8")
print(f"Wrote docs/DATA_QUALITY_REPORT.md ({sum(len(v) for v in by_code.values())} findings in {len(by_code)} categories)")
